CREATE TYPE project_type AS ENUM ('client', 'internal');

CREATE TYPE project_status AS ENUM ('not_started', 'in_progress', 'on_hold', 'completed', 'cancelled');

CREATE TYPE document_category AS ENUM ('requirements', 'quotations', 'agreements', 'designs', 'other');

CREATE TABLE users (
 id varchar(255) PRIMARY KEY, email varchar(320) NOT NULL UNIQUE,
 display_name varchar(120) NOT NULL, avatar_url text, is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());

CREATE TABLE projects (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_number integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
 name varchar(180) NOT NULL, description text, type project_type NOT NULL DEFAULT 'client',
 client_name varchar(180), status project_status NOT NULL DEFAULT 'not_started',
 owner_selection varchar(16) NOT NULL DEFAULT 'Both',
 progress integer NOT NULL DEFAULT 0, start_date date, due_date date,
 completed_at timestamptz, archived_at timestamptz,
 created_by_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 updated_by_id varchar(255) REFERENCES users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT projects_progress_range CHECK (progress BETWEEN 0 AND 100),
 CONSTRAINT projects_completed_progress CHECK (status <> 'completed' OR progress = 100),
 CONSTRAINT projects_owner CHECK (owner_selection IN ('Kabir','Naushad','Both')),
 CONSTRAINT projects_client_type CHECK (type = 'internal' OR client_name IS NOT NULL)
);

CREATE TABLE project_members (
 project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 user_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 assigned_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(project_id,user_id));

CREATE TABLE project_notes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 body text NOT NULL CHECK (length(btrim(body)) > 0),
 author_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now());

CREATE TABLE project_holds (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 reason text NOT NULL CHECK (length(btrim(reason)) > 0),
 previous_status project_status NOT NULL CHECK (previous_status <> 'on_hold'),
 started_by_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 started_at timestamptz NOT NULL DEFAULT now(),
 resumed_by_id varchar(255) REFERENCES users(id) ON DELETE SET NULL,
 resumed_at timestamptz, resolution_note text,
 CONSTRAINT holds_resumed_after_started CHECK (resumed_at IS NULL OR resumed_at >= started_at));

CREATE TABLE project_documents (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 category document_category NOT NULL DEFAULT 'other',
 original_name text NOT NULL,
 mime_type varchar(255) NOT NULL,
 size_bytes integer NOT NULL CHECK (size_bytes > 0),
 storage_key text NOT NULL UNIQUE,
 uploaded_by_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 uploaded_at timestamptz NOT NULL DEFAULT now(),
 deleted_at timestamptz, deleted_by_id varchar(255) REFERENCES users(id) ON DELETE SET NULL);

CREATE TABLE activity_logs (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 actor_id varchar(255) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 action varchar(80) NOT NULL,
 details jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now());

CREATE INDEX projects_status_idx ON projects(status);

CREATE INDEX projects_due_date_idx ON projects(due_date);

CREATE INDEX projects_updated_at_idx ON projects(updated_at);

CREATE INDEX projects_archived_at_idx ON projects(archived_at);

CREATE INDEX project_members_user_idx ON project_members(user_id);

CREATE INDEX project_notes_project_created_idx ON project_notes(project_id,created_at DESC);

CREATE UNIQUE INDEX project_holds_one_active_per_project ON project_holds(project_id) WHERE resumed_at IS NULL;

CREATE INDEX project_holds_project_started_idx ON project_holds(project_id,started_at DESC);

CREATE INDEX project_documents_project_uploaded_idx ON project_documents(project_id,uploaded_at DESC);

CREATE INDEX activity_logs_project_created_idx ON activity_logs(project_id,created_at DESC);
